const seedKnowledge = async () => {
  console.log('开始添加小麦病虫害知识库数据...');

  for (const item of knowledgeData) {
    try {
      const existing = await prisma.knowledgeDocument.findFirst({
        where: { title: item.title, isDeleted: false },
      });

      if (existing) {
        console.log(`跳过已存在的文档: ${item.title}`);
        continue;
      }

      const result = await createKnowledgeDocument(
        item.title,
        item.content,
        item.source
      );

      console.log(`成功添加文档: ${item.title}, 生成 ${result.knowledge.chunkCount} 个分块`);
    } catch (error) {
      console.error(`添加文档失败: ${item.title}`, error);
    }
  }

  console.log('知识库数据添加完成！');
  await prisma.$disconnect();
};

seedKnowledge().catch((error) => {
  console.error('种子脚本执行失败:', error);
  process.exit(1);
});